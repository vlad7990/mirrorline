"""The render leg, end to end: four beats of one clip become one short.

Every byte of footage here is generated by ffmpeg inside the test run, as
`conftest.py` explains — non-negotiable 1 holds in tests too.

Two skips are load-bearing rather than defensive:

* `needs_ffmpeg` — no binary, no render.
* `needs_ass` — **the Homebrew ffmpeg on the laptop this was written on has no
  libass** (docs/DECISIONS.md D16), so the caption burn cannot run there. The
  worker image ships the pinned LGPL build, which does carry libass, and CI
  installs a Debian ffmpeg that also does. So this test runs in both places
  that matter and skips loudly on the one that cannot.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from pipeline.ffmpeg import (
    _OPENH264,
    _X264,
    concat_filter,
    has_filter,
    pick_h264_encoder,
    probe,
    render_segments,
)
from pipeline.short import MAX_SHORT_SECONDS, MIN_SHORT_SECONDS, read_plan, render_short

from .conftest import BRAND_JSON, SENTENCES, build_transcript, needs_ffmpeg

pytestmark = pytest.mark.ffmpeg

needs_ass = pytest.mark.skipif(
    not has_filter("ass"),
    reason="this ffmpeg has no libass (D16); the worker image and CI both do",
)

#: Four of the fixture's sentences, as an approved script's four beats.
BEATS = (
    ("Hook", SENTENCES[0]),
    ("Setup", SENTENCES[4]),
    ("Payoff", SENTENCES[6]),
    ("Call to action", SENTENCES[12]),
)


def write_plan(tmp_path: Path, source: Path) -> Path:
    transcript = build_transcript()
    plan = {
        "source": str(source),
        "out": str(tmp_path / "out"),
        "title": "What new managers get wrong",
        "hook": "Burnout is not a workload problem",
        "beats": [{"label": label, "text": text} for label, text in BEATS],
        "words": [
            {"text": word.text, "start": word.start_s, "end": word.end_s}
            for word in transcript.words
        ],
        "brand": BRAND_JSON,
    }
    path = tmp_path / "plan.json"
    path.write_text(json.dumps(plan, indent=2), encoding="utf-8")
    return path


class TestConcatFilter:
    """Pure string assertions: no ffmpeg needed and the subtle part is here."""

    def test_rebases_every_window_to_zero(self) -> None:
        graph, video, audio = concat_filter(((2.0, 8.0), (20.0, 26.0)), with_audio=True)

        # Without the rebase, a trimmed stream keeps its source timestamps and
        # the concat filter produces a video with a ten-minute gap in it.
        assert graph.count(",setpts=PTS-STARTPTS") == 2
        assert graph.count(",asetpts=PTS-STARTPTS") == 2
        assert "concat=n=2:v=1:a=1[vcat][acat]" in graph
        assert (video, audio) == ("vcat", "acat")

    def test_reframes_each_window_before_joining(self) -> None:
        graph, _, _ = concat_filter(((0.0, 4.0),), with_audio=False)
        assert graph.count("crop=1080:1920") == 1
        assert "concat=n=1:v=1:a=0[vcat]" in graph

    def test_adds_the_caption_burn_last(self) -> None:
        graph, video, _ = concat_filter(((0.0, 4.0),), with_audio=True, ass_path=Path("/w/c.ass"))
        # After the concat, so the caption times are the finished video's times
        # rather than each window's.
        assert graph.index("concat=") < graph.index("ass=")
        assert video == "vout"

    def test_escapes_a_path_the_filter_parser_would_eat(self) -> None:
        graph, _, _ = concat_filter(((0, 4),), with_audio=True, ass_path=Path("/w/od:d/c.ass"))
        assert r"/w/od\:d/c.ass" in graph


class TestEncoderChoice:
    def test_prefers_the_lgpl_encoder_when_the_build_has_it(self) -> None:
        chosen = pick_h264_encoder()
        assert chosen in (_OPENH264, _X264)
        # The flags travel with the choice, because passing x264's -crf to
        # openh264 does not fail loudly — it is ignored.
        if chosen is _OPENH264:
            assert "-b:v" in chosen.args and chosen.is_lgpl
        else:
            assert "-crf" in chosen.args and not chosen.is_lgpl


@needs_ffmpeg
class TestRenderSegments:
    def test_joins_two_windows_into_one_vertical_file(
        self, source_video: Path, tmp_path: Path
    ) -> None:
        out = render_segments(
            source_video,
            tmp_path / "short.mp4",
            ((2.0, 8.0), (20.0, 26.0)),
            with_audio=True,
        )

        made = probe(out)
        assert (made.width, made.height) == (1080, 1920)
        # Two six-second windows. Frame-accurate trimming is not exact, so the
        # assertion is "about twelve seconds" rather than a fiction.
        assert 11.0 <= made.duration_s <= 13.0
        assert made.has_audio

    def test_refuses_a_short_with_no_windows(self, source_video: Path, tmp_path: Path) -> None:
        with pytest.raises(Exception):
            render_segments(source_video, tmp_path / "none.mp4", ())


@needs_ffmpeg
@needs_ass
class TestRenderShort:
    def test_four_beats_become_one_captioned_short(
        self, source_video: Path, tmp_path: Path
    ) -> None:
        outcome = render_short(read_plan(write_plan(tmp_path, source_video)))

        assert outcome.short_path.exists()
        assert outcome.poster_path.exists()
        assert outcome.captions_path.exists()
        assert MIN_SHORT_SECONDS <= outcome.duration_s <= MAX_SHORT_SECONDS

        made = probe(outcome.short_path)
        assert (made.width, made.height) == (1080, 1920)
        assert made.has_audio

    def test_the_summary_says_what_it_actually_did(
        self, source_video: Path, tmp_path: Path
    ) -> None:
        outcome = render_short(read_plan(write_plan(tmp_path, source_video)))
        summary = json.loads(outcome.summary_path.read_text(encoding="utf-8"))

        assert summary["ok"] is True
        assert [segment["beat"] for segment in summary["segments"]] == [
            "Hook",
            "Setup",
            "Payoff",
            "Call to action",
        ]
        # Every beat's coverage is carried, so a weak match is visible rather
        # than implied by a video nobody can use.
        assert all(segment["coverage"] >= 0.4 for segment in summary["segments"])

        # The engine says `pass`; the database's constraint reads `passed`. The
        # mapping lives in one place and this is the assertion on it.
        assert summary["compliance"]["verdict"] == "passed"

        # The two honesty fields: which encoder, and whether the client's own
        # brand face was available.
        assert summary["encoder"]["name"] in ("libopenh264", "libx264")
        assert isinstance(summary["font"]["isBrandFont"], bool)

        # Slice 1 generates nothing, so the AI slot is empty — and an empty
        # list is what `renders.ai_scenes` needs to skip the label constraint.
        assert summary["aiScenes"] == []

    def test_the_captions_are_on_the_finished_timeline(
        self, source_video: Path, tmp_path: Path
    ) -> None:
        outcome = render_short(read_plan(write_plan(tmp_path, source_video)))
        captions = outcome.captions_path.read_text(encoding="utf-8")

        dialogues = [line for line in captions.splitlines() if line.startswith("Dialogue:")]
        assert len(dialogues) > 4

        # The source windows start at 0s, 69s, 96s and 165s. If any caption
        # carried a source timestamp it would sit past the end of a 52-second
        # video and never appear — the bug this assertion exists for.
        assert all(":00:" in line.split(",")[1] or ":01:" in line.split(",")[1] for line in dialogues)
        assert "The thing" not in captions  # nothing invents words

    def test_refuses_a_plan_whose_beat_is_not_in_the_footage(
        self, source_video: Path, tmp_path: Path
    ) -> None:
        plan_path = write_plan(tmp_path, source_video)
        plan = json.loads(plan_path.read_text(encoding="utf-8"))
        plan["beats"][2]["text"] = "the quarterly margin on wholesale pallets in Rotterdam"
        plan_path.write_text(json.dumps(plan), encoding="utf-8")

        from pipeline.beats import BeatNotFound

        with pytest.raises(BeatNotFound) as raised:
            render_short(read_plan(plan_path))

        assert raised.value.label == "Payoff"
